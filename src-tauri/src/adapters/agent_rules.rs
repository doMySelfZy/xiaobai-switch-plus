/// 托管块标记。用 HTML 注释是因为它在 Markdown 渲染里不可见，同时又是纯文本行，
/// 便于用户人肉定位与 grep。前缀与 MCP 的 `xiaobai_` 命名空间同源。
const RULE_BEGIN: &str = "<!-- xiaobai-switch:begin global-rules -->";
const RULE_END: &str = "<!-- xiaobai-switch:end global-rules -->";
/// 写在块里的固定提示。它是落进目标文件的文件内容（可能跨语言切换后残留），
/// 不是 UI 文案，所以这里是 i18n 约定的有意例外：固定双语，不随界面语言变。
const RULE_NOTICE: &str = "<!-- Generated by XiaoBaiSwitch Plus · 由 XiaoBaiSwitch Plus 生成，请勿在此块内手工编辑 -->";

const BOM: &str = "\u{feff}";

fn render_block(body: &str) -> String {
    let trimmed = body.trim_end_matches(['\n', '\r']);
    format!("{RULE_BEGIN}\n{RULE_NOTICE}\n{trimmed}\n{RULE_END}")
}

fn validate_body(body: &str) -> AppResult<()> {
    if body.contains(RULE_BEGIN) || body.contains(RULE_END) || body.contains(RULE_NOTICE) {
        return Err(AppError::new(
            "validation_failed",
            "the rules text must not contain the XiaoBaiSwitch managed-block markers",
        ));
    }
    Ok(())
}

/// 落库前的校验：标记字面量写进数据库后无法可靠界定托管块，必须在保存前拦下。
pub fn validate_body_for_storage(body: &str) -> AppResult<()> {
    validate_body(body)
}

/// 删除全部托管块并返回剩余内容与删除的块数。
///
/// - 出现 BEGIN 但之后没有配对的 END：报错（文件被手工改坏，不能猜着改）。
/// - 只有 END 没有 BEGIN：不报错，按用户自己的内容原样保留。
fn strip_blocks(text: &str) -> AppResult<(String, usize)> {
    let mut out = String::with_capacity(text.len());
    let mut removed = 0;
    let mut rest = text;
    while let Some(begin_at) = rest.find(RULE_BEGIN) {
        out.push_str(&rest[..begin_at]);
        let after_begin = &rest[begin_at..];
        let Some(end_rel) = after_begin.find(RULE_END) else {
            return Err(AppError::new(
                "invalid_config",
                "the managed block has a start marker but no end marker",
            ));
        };
        removed += 1;
        rest = &after_begin[end_rel + RULE_END.len()..];
    }
    out.push_str(rest);
    Ok((out, removed))
}

/// 把剩余内容收拾成「块外内容 + 恰好一个末尾换行」。
fn tidy_remainder(text: &str) -> String {
    let trimmed = text.trim_end_matches(['\n', '\r']);
    if trimmed.trim().is_empty() {
        return String::new();
    }
    format!("{trimmed}\n")
}

/// 计算写入后的完整文件内容。`None` 表示要求清掉托管块。
///
/// 返回新内容与是否真的发生了变化；内容不变时调用方必须跳过写盘与备份，
/// 否则每次保存都会无谓地触碰客户端文件、污染备份目录。
fn apply_block(text: &str, block: Option<&str>) -> AppResult<(String, bool)> {
    let (remainder, removed) = strip_blocks(text)?;
    // 要求清理、而文件里本来就没有托管块：原样返回，绝不去顺带整理用户的空行。
    if block.is_none() && removed == 0 {
        return Ok((text.to_string(), false));
    }
    let next = match block {
        Some(block) => {
            let base = tidy_remainder(&remainder);
            if base.is_empty() {
                format!("{block}\n")
            } else {
                // 尾部已有换行时 tidy_remainder 保证只留一个，这里再补一个空行分隔。
                format!("{base}\n{block}\n")
            }
        }
        None => tidy_remainder(&remainder),
    };
    let changed = next != text;
    Ok((next, changed))
}

struct Loaded {
    text: String,
    had_bom: bool,
    existed: bool,
}

fn read_target(path: &Path) -> AppResult<Loaded> {
    if path.is_dir() {
        return Err(AppError::new(
            "invalid_config",
            format!("{} is a directory, not a file", path.display()),
        ));
    }
    if !path.exists() {
        return Ok(Loaded {
            text: String::new(),
            had_bom: false,
            existed: false,
        });
    }
    let bytes = fs::read(path)?;
    let text = String::from_utf8(bytes).map_err(|_| {
        AppError::new(
            "invalid_config",
            format!("{} is not valid UTF-8", path.display()),
        )
    })?;
    Ok(Loaded {
        had_bom: text.starts_with(BOM),
        text,
        existed: true,
    })
}

/// 把一段正文写进某个目标文件，或（`body = None`）把托管块清理掉。
pub fn apply_to_path(
    path: &Path,
    body: Option<&str>,
    backup_root: &Path,
) -> AppResult<AgentRulesTargetResult> {
    let label = path.display().to_string();
    if let Some(body) = body {
        validate_body(body)?;
    }
    let block = body.map(render_block);

    // 与目标 CLI（以及本应用其他适配器）对同一个文件的读写互斥。
    let _lock = FileLock::acquire(path)?;
    let loaded = read_target(path)?;
    let (next, changed) = apply_block(&loaded.text, block.as_deref())?;

    if !changed {
        return Ok(AgentRulesTargetResult {
            target: TargetKind::ClaudeCode,
            ok: true,
            path: label,
            changed: false,
            backup_paths: Vec::new(),
            message: "no change".to_string(),
        });
    }

    let mut backup_paths = Vec::new();
    if loaded.existed {
        backup_paths.push(backup_file(path, backup_root)?.display().to_string());
    }

    let empty = next.trim().is_empty();
    if empty && loaded.existed {
        // 整个文件都是本应用写的：删掉它，否则 Pi/Prime 会把空的 AGENTS.md
        // 当成优先文件，反而遮蔽用户自己的 CLAUDE.md。
        fs::remove_file(path)?;
    } else if !next.is_empty() {
        let payload = if loaded.had_bom {
            format!("{BOM}{next}")
        } else {
            next.clone()
        };
        atomic_write(path, payload.as_bytes(), false)?;
    }

    Ok(AgentRulesTargetResult {
        target: TargetKind::ClaudeCode,
        ok: true,
        path: label,
        changed: true,
        backup_paths,
        message: if body.is_some() {
            "applied".to_string()
        } else {
            "cleared".to_string()
        },
    })
}

/// Codex 的 `AGENTS.override.md` 会整体遮蔽 `AGENTS.md`：只检测并回报给 UI，不改写它。
fn codex_override_shadow(codex_home: &Path) -> Option<String> {
    let override_path = codex_home.join("AGENTS.override.md");
    override_path
        .is_file()
        .then(|| override_path.display().to_string())
}

/// Pi/Prime 的目标文件选择：已有 `AGENTS.md` 用它；否则已有 `CLAUDE.md` 就追加进
/// `CLAUDE.md`（新建 `AGENTS.md` 会让用户手写的 `CLAUDE.md` 被整体遮蔽）；都没有则新建
/// `AGENTS.md`（两个 CLI 文档里的首选文件名）。
fn agents_or_claude(agent_dir: &Path) -> PathBuf {
    let agents = agent_dir.join("AGENTS.md");
    if agents.is_file() {
        return agents;
    }
    let claude = agent_dir.join("CLAUDE.md");
    if claude.is_file() {
        return claude;
    }
    agents
}

fn target_path(target: TargetKind, overrides: &TargetOverrides) -> AppResult<PathBuf> {
    Ok(match target {
        TargetKind::ClaudeCode => claude_rules_path(overrides.claude_home.as_deref())?,
        TargetKind::Codex => resolve_codex_home(overrides.codex_home.as_deref())?.join("AGENTS.md"),
        TargetKind::Pi => agents_or_claude(&resolve_pi_agent_dir(overrides.pi_agent_dir.as_deref())?),
        TargetKind::Prime => {
            agents_or_claude(&resolve_prime_agent_dir(overrides.prime_agent_dir.as_deref())?)
        }
    })
}

/// 四个目标的用户级 override 设置（与 `commands/apply.rs` 用的是同一批字段）。
#[derive(Debug, Default, Clone)]
pub struct TargetOverrides {
    pub claude_home: Option<String>,
    pub codex_home: Option<String>,
    pub pi_agent_dir: Option<String>,
    pub prime_agent_dir: Option<String>,
}

pub fn target_paths(overrides: &TargetOverrides) -> AppResult<Vec<(TargetKind, PathBuf)>> {
    [
        TargetKind::ClaudeCode,
        TargetKind::Codex,
        TargetKind::Pi,
        TargetKind::Prime,
    ]
    .into_iter()
    .map(|target| Ok((target, target_path(target, overrides)?)))
    .collect()
}

pub fn codex_shadow(overrides: &TargetOverrides) -> AppResult<Option<String>> {
    Ok(codex_override_shadow(&resolve_codex_home(
        overrides.codex_home.as_deref(),
    )?))
}

/// 把一个目标写盘（或清理），并把结果里的 `target` 字段修正为该目标。
pub fn apply_to_target(
    target: TargetKind,
    body: Option<&str>,
    overrides: &TargetOverrides,
    backup_root: &Path,
) -> AppResult<AgentRulesTargetResult> {
    let path = target_path(target, overrides)?;
    let mut result = apply_to_path(&path, body, backup_root)?;
    result.target = target;
    Ok(result)
}

