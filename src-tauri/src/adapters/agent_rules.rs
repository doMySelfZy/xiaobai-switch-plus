    fn strip_blocks_removes_managed_blocks_and_keeps_user_text() {
        let text = format!("用户内容\n\n{}\n\n用户尾部\n", render_block("正文"));
        let (remainder, removed) = strip_blocks(&text).unwrap();
        assert_eq!(removed, 1);
        assert!(!remainder.contains(RULE_BEGIN));
        assert!(remainder.contains("用户内容"));
        assert!(remainder.contains("用户尾部"));
    }

